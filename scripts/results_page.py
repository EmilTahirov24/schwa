"""docs/results.md, kept as named sections, each one owned by the script that measures it.

A script replaces its own section and leaves the others alone, so running one evaluation
never erases the numbers of another. The headline numbers also go to docs/results.json, for
the code that shows them - the demo page - and for the test that holds the README to them.
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path("docs/results.md")
NUMBERS = Path("docs/results.json")

INTRO = """# Results

Generated by the scripts in `scripts/`, never edited by hand. Ambiguous word accuracy is the
headline number: it covers only the words whose typed form stands for more than one real
word, which is the part a model can actually get wrong.
"""


# Sections are kept in this order, whichever script ran last; "errors (test)" sorts as "errors".
ORDER = (
    "dev",
    "test",
    "web_dev",
    "web_test",
    "domain shift",
    "ambiguity threshold",
    "names",
    "errors",
    "spelling",
    "quantisation",
    "text",
)


def rank(title: str) -> int:
    kind = title.split(" (")[0]
    return ORDER.index(kind) if kind in ORDER else len(ORDER)


def write_section(title: str, body: str, path: Path = RESULTS) -> None:
    """Put `### title` in place of the old section of that name, keeping every other one."""
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    sections: dict[str, str] = {}
    for part in text.split("\n### ")[1:]:
        name, _, content = part.partition("\n")
        sections[name.strip()] = content.strip()
    sections[title] = body.strip()

    ordered = sorted(sections.items(), key=lambda item: rank(item[0]))
    page = "\n\n".join([INTRO.strip(), *(f"### {name}\n\n{content}" for name, content in ordered)])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(page + "\n", encoding="utf-8", newline="\n")


def write_numbers(name: str, numbers: dict, path: Path = NUMBERS) -> None:
    """Replace the entry `name` of docs/results.json, keeping the others."""
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    data[name] = numbers
    text = json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")
